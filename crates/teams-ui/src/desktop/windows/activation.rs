//! Unpackaged desktop notifications activate through COM, including while the app is already running.
//! The callback only queues opaque arguments; the owning toast center validates them against its live notices.
use std::sync::Arc;
use windows::{
    Win32::{
        Foundation::{CLASS_E_NOAGGREGATION, E_POINTER},
        System::Com::{
            CLSCTX_LOCAL_SERVER, CoRegisterClassObject, CoRevokeClassObject, IClassFactory, IClassFactory_Impl,
            REGCLS_MULTIPLEUSE,
        },
        UI::Notifications::{
            INotificationActivationCallback, INotificationActivationCallback_Impl, NOTIFICATION_USER_INPUT_DATA,
        },
    },
    core::{BOOL, GUID, IUnknown, Interface as _, PCWSTR, Ref, Result, implement},
};

type Handler = Arc<dyn Fn(String) + Send + Sync>;

pub(super) struct Activator(u32);
impl Activator {
    pub(super) fn register(
        app_id: &str,
        clsid: &GUID,
        handler: impl Fn(String) + Send + Sync + 'static,
    ) -> Result<Self> {
        let callback: INotificationActivationCallback = com::Callback {
            app_id: app_id.into(),
            handler: Arc::new(handler),
        }
        .into();
        let factory: IClassFactory = com::Factory(callback).into();
        // SAFETY: this MTA owns the registration, and COM retains the agile factory until revocation.
        unsafe { CoRegisterClassObject(clsid, &factory, CLSCTX_LOCAL_SERVER, REGCLS_MULTIPLEUSE) }.map(Self)
    }
}
impl Drop for Activator {
    fn drop(&mut self) {
        // SAFETY: balances the successful registration on its owning thread, before apartment shutdown.
        let _ = unsafe { CoRevokeClassObject(self.0) };
    }
}

// These operations are generated by windows-rs' COM implementation macro.
#[expect(
    clippy::ref_as_ptr,
    clippy::inline_always,
    reason = "windows-rs generated COM ABI implementations"
)]
mod com {
    use super::*;
    #[implement(INotificationActivationCallback)]
    pub(super) struct Callback {
        pub(super) app_id: String,
        pub(super) handler: Handler,
    }
    impl INotificationActivationCallback_Impl for Callback_Impl {
        fn Activate(
            &self,
            app_id: &PCWSTR,
            arguments: &PCWSTR,
            _data: *const NOTIFICATION_USER_INPUT_DATA,
            _count: u32,
        ) -> Result<()> {
            if app_id.is_null() || arguments.is_null() {
                return Err(E_POINTER.into());
            }
            // SAFETY: COM supplies terminated strings valid for the duration of this call; neither pointer escapes.
            if unsafe { app_id.to_string()? } == self.app_id {
                // SAFETY: the same COM-owned input string, copied before returning to the shell.
                (self.handler)(unsafe { arguments.to_string()? });
            }
            Ok(())
        }
    }

    #[implement(IClassFactory)]
    pub(super) struct Factory(pub(super) INotificationActivationCallback);
    impl IClassFactory_Impl for Factory_Impl {
        fn CreateInstance(
            &self,
            outer: Ref<IUnknown>,
            iid: *const GUID,
            object: *mut *mut std::ffi::c_void,
        ) -> Result<()> {
            if object.is_null() || iid.is_null() {
                return Err(E_POINTER.into());
            }
            // SAFETY: COM supplies a writable result pointer; initialize it even on aggregation refusal.
            unsafe { object.write(std::ptr::null_mut()) };
            if !outer.is_null() {
                return Err(CLASS_E_NOAGGREGATION.into());
            }
            // SAFETY: validated COM out-pointer and IID; QueryInterface adds a reference on success.
            unsafe { self.0.query(iid, object) }.ok()
        }
        fn LockServer(&self, _lock: BOOL) -> Result<()> {
            Ok(())
        }
    }
}
